#!/usr/bin/env node
// Writes dapp/cbtc/history-base.js: the collateral engine's events up to a settled block (128 blocks behind the head), so the /cbtc/ page reads only
// what came after. Events do not change, so the page need not ask a public node for 400,000 blocks of logs on every visit (the one node that took
// that range in one request is a shared free key, and the others fail it); it asks for the few blocks since this file was written. Run it again
// whenever the page's tail has grown long (the page still works without: each day adds about one more request).
//
//   node tools/cbtc-history-base.mjs
import { writeFileSync } from 'node:fs';
import { ETH_LOG_NODES, refuses } from '../dapp/eth-nodes.js';
import { FIRST_BLOCK, SPAN, filterFor, withTimes, eventsOf } from '../dapp/cbtc/events.js';

async function call(method, params) {
  let last;
  for (let round = 0; round < 3; round++) {
    for (const url of ETH_LOG_NODES) {
      if (refuses(url, method, params)) continue;
      try {
        const j = await (await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }), signal: AbortSignal.timeout(20000) })).json();
        if (j.error) throw new Error(j.error.message);
        return j.result;
      } catch (e) { last = e; }
    }
    await new Promise((r) => setTimeout(r, 1500));
  }
  throw new Error(`no node answered ${method}: ${last?.message}`);
}

const head = Number(BigInt(await call('eth_blockNumber', []))), block = head - 128;
const logs = [];
for (let from = FIRST_BLOCK; from <= block; from += SPAN) logs.push(...await call('eth_getLogs', [filterFor(from, Math.min(from + SPAN - 1, block))]));
const { posted, loans } = eventsOf(await withTimes(logs, async (b) => Number(BigInt((await call('eth_getBlockByNumber', [b, false])).timestamp))));

const rows = (list) => list.map((r) => `  ${JSON.stringify(r)},\n`).join('');
const file = new URL('../dapp/cbtc/history-base.js', import.meta.url);
writeFileSync(file, `// Generated by tools/cbtc-history-base.mjs: the collateral engine's events up to block ${block}, kept as ([time, outpoint]) for each lock's first posted bond and
// ([time, cUSD at 8 decimals]) for each change in what is lent. The page reads the blocks after \`block\` itself (cbtc/read.js).
export const BASE = {
  block: ${block},
  posted: [
${rows(posted)}  ],
  loans: [
${rows(loans)}  ],
};
`);
console.log(`${logs.length} events up to block ${block}: ${posted.length} locks posted, ${loans.length} loan changes -> ${file.pathname}`);
